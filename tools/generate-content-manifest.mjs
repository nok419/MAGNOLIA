#!/usr/bin/env node

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const rootDir = process.cwd()
const gameplayDir = path.join(rootDir, "content", "gameplay")
const manifestPath = path.join(
  rootDir,
  "packages",
  "persistence",
  "src",
  "generated",
  "content-manifest.ts",
)

const options = new Set(process.argv.slice(2))
const checkOnly = options.has("--check")
if ([...options].some((option) => option !== "--check")) {
  throw new Error(`Unsupported argument: ${[...options].find((option) => option !== "--check")}`)
}

const groups = [
  { exportName: "areas", roots: ["areas"], flattenArrays: false },
  { exportName: "backgroundPresets", roots: ["background-presets"], flattenArrays: false },
  { exportName: "bulletPatterns", roots: ["bullet-patterns"], flattenArrays: false },
  { exportName: "enemies", roots: ["enemies"], flattenArrays: false },
  { exportName: "equipment", roots: ["equipment"], flattenArrays: false, excludePrefix: "equipment/effects/" },
  { exportName: "effects", roots: ["equipment/effects"], flattenArrays: false },
  { exportName: "hitboxPresets", roots: ["hitbox-presets"], flattenArrays: false },
  { exportName: "mapLogic", roots: ["map-logic"], flattenArrays: false },
  { exportName: "missions", roots: ["missions"], flattenArrays: false },
  { exportName: "conditions", roots: ["progression/conditions"], flattenArrays: false },
  { exportName: "projectiles", roots: ["projectiles"], flattenArrays: false },
  { exportName: "transmissions", roots: ["transmissions"], flattenArrays: false, excludeSuffix: ".chunks.json" },
  { exportName: "transcriptChunks", roots: ["transmissions"], flattenArrays: true, includeSuffix: ".chunks.json" },
  { exportName: "visualPresets", roots: ["visual-presets"], flattenArrays: false },
]

const importEntries = []
const exportLines = []

for (const group of groups) {
  const files = collectGroupFiles(group)
  const variables = files.map((relativePath) => addImport(relativePath))
  const values = group.flattenArrays
    ? variables.map((variable) => `...${variable}`)
    : variables
  exportLines.push(`  ${group.exportName}: [${values.join(", ")}],`)
}

const contentClassificationVariable = addImport("content-classification.json")
const presentationCuesVariable = addImport("presentation-cues.json")
exportLines.push(`  contentClassification: ${contentClassificationVariable},`)
exportLines.push(`  presentationCues: ${presentationCuesVariable},`)

const source = [
  "/*",
  " * This file is generated by tools/generate-content-manifest.mjs.",
  " * Run `npm run content:manifest` after adding gameplay JSON.",
  " */",
  "",
  ...importEntries.map(({ variableName, importPath }) => `import ${variableName} from "${importPath}"`),
  "",
  "export const contentManifest = {",
  ...exportLines,
  "} as const",
  "",
].join("\n")

if (checkOnly) {
  const current = existsSync(manifestPath) ? readFileSync(manifestPath, "utf8") : ""
  if (current !== source) {
    throw new Error("content manifest is stale. Run `npm run content:manifest`.")
  }
  console.log("content manifest is up to date")
} else {
  mkdirSync(path.dirname(manifestPath), { recursive: true })
  writeFileSync(manifestPath, source)
  console.log(`content manifest written: ${path.relative(rootDir, manifestPath)}`)
}

function collectGroupFiles(group) {
  const files = group.roots.flatMap((root) => collectJsonFiles(path.join(gameplayDir, root)))
  return files
    .map((file) => path.relative(gameplayDir, file).split(path.sep).join("/"))
    .filter((relativePath) => !group.includeSuffix || relativePath.endsWith(group.includeSuffix))
    .filter((relativePath) => !group.excludeSuffix || !relativePath.endsWith(group.excludeSuffix))
    .filter((relativePath) => !group.excludePrefix || !relativePath.startsWith(group.excludePrefix))
    .sort()
}

function collectJsonFiles(dir) {
  if (!existsSync(dir)) {
    return []
  }

  const files = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const entryPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...collectJsonFiles(entryPath))
      continue
    }
    if (entry.isFile() && entry.name.endsWith(".json")) {
      files.push(entryPath)
    }
  }
  return files
}

function addImport(relativePath) {
  const variableName = toImportName(relativePath)
  const importPath = `../../../../content/gameplay/${relativePath}`
  importEntries.push({ variableName, importPath })
  return variableName
}

function toImportName(relativePath) {
  const base = relativePath
    .replace(/\.chunks\.json$/, " chunks")
    .replace(/\.json$/, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part, index) => index === 0 ? part : `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`)
    .join("")
  return `${base.replace(/^[0-9]/, "_$&")}Json`
}
